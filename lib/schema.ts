let schemaReady = false
let bootstrapPromise: Promise<void> | null = null
let nextRetryAt = 0

/** Catalog races between concurrent bootstraps mean the object now exists. */
function isBenignSchemaRace(error: unknown): boolean {
  const code = (error as { code?: string } | null)?.code
  return code === '42P07' || code === '42710' || code === '42701' || code === '23505'
}

async function runBootstrap(): Promise<void> {
  // A dedicated short-lived pool: the application pool is gated on this
  // bootstrap, so querying through it would deadlock.
  const admin = new Pool({
    connectionString: process.env.DATABASE_URL,
    max: 2,
    connectionTimeoutMillis: 10_000,
  })

  try {
    for (const statement of appSchemaStatements) {
      try {
        await admin.query(statement)
      } catch (error) {
        if (!isBenignSchemaRace(error)) throw error
      }
    }

    try {
      const [{ auth }, { getMigrations }] = await Promise.all([
        import('@/lib/auth'),
        import('better-auth/db/migration'),
      ])
      const { runMigrations } = await getMigrations({ ...auth.options, database: admin })
      await runMigrations()
    } catch (error) {
      // Keep the application tables even if the auth-side migration refuses;
      // log loudly so a schema mismatch never goes unnoticed.
      console.error('[schema] Better Auth migration failed:', error instanceof Error ? error.message : error)
    }
  } finally {
    await admin.end().catch(() => undefined)
  }
}

/**
 * Create any missing tables, then resolve. Never rejects: failures are logged
 * and retried after a cooldown, so a broken database surfaces as the query's
 * own error instead of hanging every request during bootstrap.
 */
export function ensureSchema(): Promise<void> {
  if (schemaReady) return Promise.resolve()
  if (bootstrapPromise) return bootstrapPromise
  if (Date.now() < nextRetryAt) return Promise.resolve()

  bootstrapPromise = runBootstrap()
    .then(() => {
      schemaReady = true
    })
    .catch((error) => {
      console.error('[schema] Bootstrap failed:', error instanceof Error ? error.message : error)
      nextRetryAt = Date.now() + 30_000
    })
    .finally(() => {
      bootstrapPromise = null
    })
  return bootstrapPromise
}
