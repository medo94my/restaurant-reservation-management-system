import { Pool } from 'pg'

/**
 * Idempotent schema bootstrap.
 *
 * The project has no migration runner (no drizzle-kit, and every deployment
 * shares one database), so missing tables are created on demand: `lib/db.ts`
 * gates every pool query behind `ensureSchema()`, and `instrumentation.ts`
 * warms it when the server starts. Every statement is idempotent, so running
 * against an already-provisioned database is a no-op.
 *
 * Better Auth owns `user` / `session` / `account` / `verification`, so those
 * are created through Better Auth's own migration generator, which knows the
 * columns the configured plugins add (e.g. the `username` plugin's `username`
 * column and the admin plugin's `role` / `banned` fields). The application
 * tables are created from the DDL below, which mirrors the Drizzle schema in
 * `lib/db.ts` — keep the two in sync when tables change.
 */

